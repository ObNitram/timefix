/// Edits that apply to several occurrences of a recurring series ("this and
/// following", "all").
library;

import 'dart:math' as math;

import '../core/date_utils.dart';
import 'models.dart';
import 'recurrence.dart';

/// [d] moved the way [from] was moved to [to], in wall-clock time: the same
/// number of calendar days and the same change of time of day, so that a
/// series keeps its local time across DST changes.
DateTime shiftLikeMove(DateTime d, DateTime from, DateTime to, {bool allDay = false}) {
  final days = daysBetween(from, to);
  if (allDay) return DateTime(d.year, d.month, d.day + days);
  final minutes = (to.hour * 60 + to.minute) - (from.hour * 60 + from.minute);
  final seconds = to.second - from.second;
  return DateTime(d.year, d.month, d.day + days, d.hour, d.minute + minutes, d.second + seconds);
}

/// [rule] with its date-bound parts (BYDAY, BYMONTHDAY, BYMONTH) following an
/// occurrence moved from [from] to [to]: "every Monday" moved to a Tuesday
/// becomes "every Tuesday", "the 2nd Tuesday" moved to the 3rd Wednesday
/// becomes "the 3rd Wednesday", "the 15th" moved to the 16th becomes "the
/// 16th". Values that do not match the old date are kept, and a part is left
/// as it is when the new value is already in it.
String rruleMovedBy(String rule, DateTime from, DateTime to) {
  if (daysBetween(from, to) == 0) return rule;
  final parts = Map.of(parseRrule(rule).parts);

  final byDay = parts['BYDAY'];
  if (byDay != null) {
    final oldCode = weekdayCode(from), newCode = weekdayCode(to);
    final updated = <String>[];
    var changed = false;
    for (final item in byDay.split(',')) {
      final m = RegExp(r'^([+-]?\d+)?([A-Za-z]{2})$').firstMatch(item.trim());
      if (m == null || m.group(2)!.toUpperCase() != oldCode) {
        updated.add(item);
        continue;
      }
      final ordinal = m.group(1);
      if (ordinal == null) {
        updated.add(newCode);
        changed = true;
        continue;
      }
      // A day with its position in the month: "2TU", "-1FR" (last Friday).
      final n = int.parse(ordinal);
      if (n != _ordinal(from, fromEnd: n < 0)) {
        updated.add(item);
        continue;
      }
      updated.add('${_ordinal(to, fromEnd: n < 0)}$newCode');
      changed = true;
    }
    if (changed && updated.toSet().length == updated.length) parts['BYDAY'] = updated.join(',');
  }

  for (final (key, old, now) in [
    ('BYMONTHDAY', '${from.day}', '${to.day}'),
    ('BYMONTH', '${from.month}', '${to.month}'),
  ]) {
    final items = parts[key]?.split(',');
    if (items == null || !items.contains(old) || items.contains(now)) continue;
    parts[key] = [for (final i in items) i == old ? now : i].join(',');
  }
  return _join(parts);
}

/// Position of [d]'s weekday in its month: 1 for the first, or with
/// [fromEnd] -1 for the last.
int _ordinal(DateTime d, {required bool fromEnd}) =>
    fromEnd ? -((daysInMonth(d.year, d.month) - d.day) ~/ 7 + 1) : (d.day - 1) ~/ 7 + 1;

String rruleWithCount(String rule, int count) {
  final parts = Map.of(parseRrule(rule).parts)..['COUNT'] = '$count';
  return _join(parts);
}

String _join(Map<String, String> parts) => parts.entries.map((e) => '${e.key}=${e.value}').join(';');

/// Instances generated by [master]'s rule before [before] (excluded dates
/// included: RFC 5545 counts them in COUNT).
int instancesBefore(CalendarEvent master, DateTime before) {
  final occurrences = const RecurrenceExpander()
      .occurrences(master.copyWith(exdates: const []), DateRange(master.start, before));
  return occurrences.where((o) => o.$1.isBefore(before)).length;
}

/// "This and following": the series that continues [master] from its
/// occurrence at [occurrenceStart], edited into [edited] (whose start is that
/// occurrence's new start). A rule left unchanged keeps the remaining COUNT
/// and its excluded dates, and follows the move of the occurrence; a rule
/// chosen by the user applies as it is.
CalendarEvent followingSeries(CalendarEvent master, DateTime occurrenceStart, CalendarEvent edited) {
  final rule = edited.rrule;
  if (rule == null || rule != master.rrule) return edited.copyWith(exdates: const []);
  var moved = rruleMovedBy(rule, occurrenceStart, edited.start);
  final count = parseRrule(moved).count;
  if (count != null) {
    moved = rruleWithCount(moved, math.max(1, count - instancesBefore(master, occurrenceStart)));
  }
  return edited.copyWith(
    rrule: moved,
    exdates: [
      for (final d in master.exdates)
        if (!d.isBefore(occurrenceStart)) shiftLikeMove(d, occurrenceStart, edited.start, allDay: master.allDay),
    ],
  );
}

/// "All": [master] edited into [edited], its occurrence at [occurrenceStart]
/// standing for the whole series. The series starts where its first
/// occurrence lands once moved like that occurrence was.
CalendarEvent wholeSeries(CalendarEvent master, DateTime occurrenceStart, CalendarEvent edited) {
  final start = shiftLikeMove(master.start, occurrenceStart, edited.start, allDay: edited.allDay);
  final end = edited.allDay
      ? addDays(start, daysBetween(edited.start, edited.end))
      : start.add(edited.end.difference(edited.start));
  final rule = edited.rrule;
  final ruleKept = rule != null && rule == master.rrule;
  final moved = start != master.start;
  return edited.copyWith(
    start: start,
    end: end,
    rrule: ruleKept ? rruleMovedBy(rule, occurrenceStart, edited.start) : null,
    exdates: !moved
        ? master.exdates
        : ruleKept
            ? [for (final d in master.exdates) shiftLikeMove(d, occurrenceStart, edited.start, allDay: master.allDay)]
            : const [],
  );
}
